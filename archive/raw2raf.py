def read_tiff_tag_value(f, endian: str, dtype: int, count: int, val_or_off: int) -> list:
    """Reads TIFF tag value handling inline values vs file offsets across all TIFF types."""
    TYPE_SIZES = {1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 7: 1, 8: 2, 9: 4, 10: 8, 11: 4, 12: 8}
    size = TYPE_SIZES.get(dtype, 1)
    total_bytes = count * size

    if total_bytes <= 4:
        raw_bytes = struct.pack(endian + "I", val_or_off)[:total_bytes]
    else:
        cur = f.tell()
        f.seek(val_or_off)
        raw_bytes = f.read(total_bytes)
        f.seek(cur)

    if dtype in (1, 7):  # BYTE / UNDEFINED
        return list(raw_bytes)
    elif dtype == 2:  # ASCII
        return [raw_bytes.decode("ascii", errors="ignore").rstrip("\x00")]
    elif dtype == 3:  # SHORT
        return list(struct.unpack(endian + f"{count}H", raw_bytes))
    elif dtype == 4:  # LONG
        return list(struct.unpack(endian + f"{count}I", raw_bytes))
    elif dtype == 5:  # RATIONAL
        res = []
        for i in range(count):
            num, den = struct.unpack(endian + "II", raw_bytes[i * 8 : (i + 1) * 8])
            res.append(num / den if den != 0 else 0.0)
        return res
    elif dtype == 8:  # SSHORT
        return list(struct.unpack(endian + f"{count}h", raw_bytes))
    elif dtype == 9:  # SLONG
        return list(struct.unpack(endian + f"{count}i", raw_bytes))
    elif dtype == 10:  # SRATIONAL
        res = []
        for i in range(count):
            num, den = struct.unpack(endian + "ii", raw_bytes[i * 8 : (i + 1) * 8])
            res.append(num / den if den != 0 else 0.0)
        return res
    elif dtype == 11:  # FLOAT
        return list(struct.unpack(endian + f"{count}f", raw_bytes))
    elif dtype == 12:  # DOUBLE
        return list(struct.unpack(endian + f"{count}d", raw_bytes))
    return list(raw_bytes)


def remosaic_rgb_to_bayer(rgb_bytes: bytes, width: int, height: int) -> bytes:
    """
    Remosaics a 3-channel 16-bit linear RGB image into a single-channel Bayer RGGB mosaic.
    """
    rgb_arr = array.array("H")
    rgb_arr.frombytes(rgb_bytes)
    bayer = array.array("H", [0] * (width * height))

    for y in range(height):
        y_w = y * width
        y_rgb = y * width * 3
        if y % 2 == 0:
            for x in range(0, width, 2):
                bayer[y_w + x] = rgb_arr[y_rgb + x * 3]
                bayer[y_w + x + 1] = rgb_arr[y_rgb + (x + 1) * 3 + 1]
        else:
            for x in range(0, width, 2):
                bayer[y_w + x] = rgb_arr[y_rgb + x * 3 + 1]
                bayer[y_w + x + 1] = rgb_arr[y_rgb + (x + 1) * 3 + 2]

    return bayer.tobytes()


class DngParser:
    """Parses an uncompressed DNG file generated by dnglab."""

    def __init__(self, filepath: str):
        self.filepath = filepath
        self.endian = "<"
        self.width = 0
        self.height = 0
        self.crop_x = 0
        self.crop_y = 0
        self.crop_w = 0
        self.crop_h = 0
        self.bits_per_sample = 16
        self.samples_per_pixel = 1
        self.photometric_interpretation = 32803
        self.cfa_pattern = [0, 1, 1, 2]
        self.cfa_repeat_dim = [2, 2]
        self.black_level = 1024.0
        self.white_level = 16383
        self.as_shot_neutral = [1.0, 1.0, 1.0]
        self.strip_offsets = []
        self.strip_byte_counts = []
        self.raw_pixel_length = 0
        # ActiveArea: [top, left, bottom, right] — marks unmasked sensor rows/cols.
        # Populated from tag 0xc62d or, in dnglab-generated DNGs, from tag 0xc68d.
        self.active_top = 0
        self.active_left = 0
        self.active_bottom = 0
        self.active_right = 0
        self._parse()

    def _parse(self):
        with open(self.filepath, "rb") as f:
            header = f.read(16)
            self.endian = "<" if header[:2] == b"II" else ">"
            first_ifd = struct.unpack(self.endian + "I", header[4:8])[0]

            # Read IFD0
            f.seek(first_ifd)
            num_tags = struct.unpack(self.endian + "H", f.read(2))[0]
            subifd_offsets = []

            for _ in range(num_tags):
                tag, dtype, count, val_or_off = struct.unpack(self.endian + "HHI I", f.read(12))
                if tag == 0x014a:  # SubIFDs
                    subifd_offsets = read_tiff_tag_value(f, self.endian, dtype, count, val_or_off)
                elif tag == 0xc628:  # AsShotNeutral
                    neutrals = read_tiff_tag_value(f, self.endian, dtype, count, val_or_off)
                    if neutrals and len(neutrals) >= 3:
                        self.as_shot_neutral = [float(x) for x in neutrals[:3]]

            # Fallback if no SubIFDs
            target_ifds = subifd_offsets if subifd_offsets else [first_ifd]

            # Read SubIFD 0 (Primary raw image)
            raw_ifd_off = target_ifds[0]
            f.seek(raw_ifd_off)
            s_tags = struct.unpack(self.endian + "H", f.read(2))[0]

            for _ in range(s_tags):
                stag, sdtype, scount, sval = struct.unpack(self.endian + "HHI I", f.read(12))
                val = read_tiff_tag_value(f, self.endian, sdtype, scount, sval)

                if stag == 0x0100:  # ImageWidth
                    self.width = int(val[0])
                elif stag == 0x0101:  # ImageLength
                    self.height = int(val[0])
                elif stag == 0x0102:  # BitsPerSample
                    self.bits_per_sample = int(val[0])
                elif stag == 0x0106:  # PhotometricInterpretation
                    self.photometric_interpretation = int(val[0])
                elif stag == 0x0111:  # StripOffsets
                    self.strip_offsets = [int(x) for x in val]
                elif stag == 0x0115:  # SamplesPerPixel
                    self.samples_per_pixel = int(val[0])
                elif stag == 0x0117:  # StripByteCounts
                    self.strip_byte_counts = [int(x) for x in val]
                elif stag == 0x828e:  # CFAPattern (primary CFA layout tag)
                    self.cfa_pattern = [int(x) for x in val]
                elif stag == 0xc68d:  # CFAPattern2 or ActiveArea (dnglab stores ActiveArea here)
                    # dnglab encodes ActiveArea [top, left, bottom, right] in this tag.
                    # Distinguish: a 4-value record where values exceed the Bayer range (0-3)
                    # is ActiveArea, not CFA pattern.
                    if len(val) == 4 and max(val) > 3:
                        self.active_top    = int(val[0])
                        self.active_left   = int(val[1])
                        self.active_bottom = int(val[2])
                        self.active_right  = int(val[3])
                    elif len(val) <= 4:
                        # Genuine CFA pattern override (only if CFAPattern tag 0x828e absent)
                        if self.cfa_pattern == [0, 1, 1, 2]:  # still default
                            self.cfa_pattern = [int(x) for x in val]
                elif stag == 0xc62d:  # ActiveArea (standard DNG tag: top, left, bottom, right)
                    if len(val) >= 4:
                        self.active_top    = int(val[0])
                        self.active_left   = int(val[1])
                        self.active_bottom = int(val[2])
                        self.active_right  = int(val[3])
                elif stag == 0x828d:  # CFARepeatPatternDim
                    self.cfa_repeat_dim = [int(x) for x in val]
                elif stag == 0xc61a:  # BlackLevel
                    bls = [float(x) for x in val]
                    self.black_level = sum(bls) / len(bls) if bls else 1024.0
                elif stag == 0xc61d:  # WhiteLevel
                    self.white_level = int(val[0])
                elif stag == 0xc61f:  # DefaultCropOrigin
                    if len(val) >= 2:
                        self.crop_x = int(val[0])
                        self.crop_y = int(val[1])
                elif stag == 0xc620:  # DefaultCropSize
                    if len(val) >= 2:
                        self.crop_w = int(val[0])
                        self.crop_h = int(val[1])

            self.raw_pixel_length = sum(self.strip_byte_counts)

            if self.crop_w == 0 or self.crop_h == 0:
                self.crop_w = self.width
                self.crop_h = self.height

    def read_raw_pixels(self) -> bytes:
        """Reads raw bytes concatenated across all strips (remosaicing linear RGB if needed)."""
        buf = bytearray()
        with open(self.filepath, "rb") as f:
            for off, cnt in zip(self.strip_offsets, self.strip_byte_counts):
                f.seek(off)
                buf.extend(f.read(cnt))

        # If image is a 3-channel Linear Raw (e.g. Apple iPhone ProRAW), remosaic to Bayer RGGB
        if self.samples_per_pixel == 3 or self.photometric_interpretation == 34892:
            return remosaic_rgb_to_bayer(bytes(buf), self.width, self.height)

        return bytes(buf)


