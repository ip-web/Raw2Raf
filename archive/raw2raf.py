def find_jpeg_image_start(jpeg_bytes: bytes) -> int:
    """Finds the byte offset where image tables/frames start (after APP/COM metadata segments)."""
    if len(jpeg_bytes) < 4 or jpeg_bytes[:2] != b"\xff\xd8":
        raise ValueError("Not a valid JPEG")

    pos = 2
    while pos < len(jpeg_bytes) - 1:
        if jpeg_bytes[pos] != 0xff:
            break
        marker = jpeg_bytes[pos + 1]
        # Standalone markers without length: SOI, EOI, TEM, RST0-7
        if marker in (0xd8, 0xd9, 0x01) or (0xd0 <= marker <= 0xd7):
            pos += 2
            continue
        if pos + 4 > len(jpeg_bytes):
            break
        seg_len = int.from_bytes(jpeg_bytes[pos + 2 : pos + 4], "big")
        # APP0-APP15 (0xe0 - 0xef) and COM (0xfe) are metadata segments
        if (0xe0 <= marker <= 0xef) or marker == 0xfe:
            pos += 2 + seg_len
        else:
            return pos
    return pos


def strip_jpeg_to_standard(jpeg_bytes: bytes) -> bytes:
    """
    Strips all proprietary/non-standard segments from a JPEG, keeping only the segments
    required for a standard compliant JPEG: DQT (0xdb), SOFn (0xc0-0xc3, 0xc5-0xc7,
    0xc9-0xcb, 0xcd-0xcf), DHT (0xc4), SOS (0xda) and trailing image data, EOI (0xd9).

    This removes camera-vendor APP markers (e.g. Nikon 0xab, 0x32) that appear inside
    the image scan stream and confuse JPEG parsers (including exiftool's write path).
    """
    if len(jpeg_bytes) < 4 or jpeg_bytes[:2] != b"\xff\xd8":
        return jpeg_bytes  # not a recognisable JPEG, return as-is

    # Standard JPEG marker bytes (excluding APPn, COM, standalone markers)
    SOF_MARKERS = set(range(0xc0, 0xd0)) - {0xc4, 0xc8}  # SOF0-SOF15 except DHT and reserved
    KEEP_MARKERS = (
        {0xc4,   # DHT – Huffman table
         0xdb,   # DQT – quantisation table
         0xda,   # SOS – start of scan (image data follows immediately after)
         0xd9,   # EOI – end of image
         0xdd,   # DRI – restart interval
         }
        | SOF_MARKERS
    )

    out = bytearray(b"\xff\xd8")
    pos = 2
    while pos < len(jpeg_bytes) - 1:
        if jpeg_bytes[pos] != 0xff:
            # Raw scan data after SOS — copy the rest verbatim
            out.extend(jpeg_bytes[pos:])
            break
        marker = jpeg_bytes[pos + 1]
        # Standalone markers (RST0-7, SOI, EOI, TEM)
        if marker in (0xd8, 0xd9, 0x01) or (0xd0 <= marker <= 0xd7):
            if marker == 0xd9:
                out.extend(b"\xff\xd9")
            pos += 2
            continue
        if pos + 4 > len(jpeg_bytes):
            break
        seg_len = int.from_bytes(jpeg_bytes[pos + 2 : pos + 4], "big")
        total_seg = 2 + seg_len  # marker(2) + length field + payload

        if marker in KEEP_MARKERS:
            out.extend(jpeg_bytes[pos : pos + total_seg])
            if marker == 0xda:
                # SOS: copy everything after the segment header as raw scan data
                sos_end = pos + total_seg
                out.extend(jpeg_bytes[sos_end:])
                break  # all done
        # else: skip non-standard / APPn / COM / proprietary segments
        pos += total_seg

    return bytes(out)


def splice_preview_jpeg(template_jpeg: bytes, replacement_jpeg: bytes) -> bytes:
    """
    Combines the template's Fuji EXIF/MakerNotes APP segments with the
    image stream (quantization, frame, huffman, DCT scan) of replacement_jpeg.
    This guarantees the generated RAF preserves all camera metadata IFDs while
    displaying the user's actual photo preview (or a clean blank placeholder).

    The replacement JPEG is first sanitised with strip_jpeg_to_standard() to remove
    any proprietary camera APP/scan markers (e.g. Nikon APPN markers) that would
    cause exiftool and other JPEG parsers to reject the embedded preview as corrupt.
    """
    tmpl_img_start = find_jpeg_image_start(template_jpeg)
    fuji_app_segments = template_jpeg[2:tmpl_img_start]

    # Sanitise the replacement preview: keep only standard DQT/SOF/DHT/SOS segments
    clean_replacement = strip_jpeg_to_standard(replacement_jpeg)
    repl_img_start = find_jpeg_image_start(clean_replacement)
    repl_image_stream = clean_replacement[repl_img_start:]

    return b"\xff\xd8" + fuji_app_segments + repl_image_stream


def extract_raw_preview(raw_path: str, exiftool_path: Optional[str] = None) -> Optional[bytes]:
    """
    Extracts embedded preview JPEG from a camera RAW file.

    Strategy (in priority order):
      1. exiftool -JpgFromRaw / -PreviewImage / -OtherImage — returns a clean, properly
         parsed JPEG without any proprietary scan markers.
      2. Fast binary scan of the file for the largest embedded JPEG — fallback when
         exiftool is unavailable.
    """
    if not os.path.exists(raw_path):
        return None

    # Method 1: exiftool (preferred) — returns well-formed, standard JPEGs
    tool = exiftool_path or (
        next((p for p in ("exiftool.exe", "exiftool")
              if os.path.exists(os.path.abspath(p))), None)
        or shutil.which("exiftool")
    )
    if tool:
        # Try tags in preference order: JpgFromRaw is the proper raw-converter preview;
        # PreviewImage is the larger embedded JPEG; OtherImage / ThumbnailImage as fallback.
        for tag in ("-JpgFromRaw", "-PreviewImage", "-OtherImage", "-ThumbnailImage"):
            try:
                res = subprocess.run([tool, "-b", tag, raw_path], capture_output=True)
                if res.returncode == 0 and len(res.stdout) > 16384:
                    data = res.stdout
                    if data[:3] == b"\xff\xd8\xff":
                        return data
            except Exception:
                pass

    # Method 2: Fast direct binary scan — fallback when exiftool is unavailable
    try:
        file_size = os.path.getsize(raw_path)
        scan_size = min(file_size, 64 * 1024 * 1024)
        with open(raw_path, "rb") as f:
            header_data = f.read(scan_size)

        largest_jpeg = None
        largest_len = 0
        start = 0

        while True:
            pos = header_data.find(b"\xff\xd8\xff", start)
            if pos == -1:
                break
            eoi = header_data.find(b"\xff\xd9", pos + 2)
            if eoi != -1:
                length = (eoi + 2) - pos
                if length > 16384 and length > largest_len:
                    candidate = header_data[pos : eoi + 2]
                    if b"\xff\xc0" in candidate or b"\xff\xc2" in candidate:
                        largest_len = length
                        largest_jpeg = candidate
                start = eoi + 2
            else:
                break

        if largest_jpeg is not None:
            return largest_jpeg
    except Exception:
        pass

    return None


class Gfx100sIITemplate:
    """Extracts and holds structure components from a reference Fujifilm RAF file."""

    def __init__(self, template_path: str):
        self.template_path = template_path
        self.header = bytearray()
        self.jpeg_data = b""
        self.meta_data = bytearray()
        self.raw_head = bytearray()
        self.width = 11808
        self.height = 8754
        self.default_crop_w = 11648
        self.default_crop_h = 8736
        self.default_crop_top = 7
        self.default_crop_left = 8
        self.black_level = 1024
        self.bits_per_sample = 14
        self.subifd_offsets = {}
        self.camera_model = "GFX 100S II"
        self._load()

    def _load(self):
        if not os.path.exists(self.template_path):
            raise FileNotFoundError(f"Template RAF file not found: {self.template_path}")

        with open(self.template_path, "rb") as f:
            self.header = bytearray(f.read(148))
            jpeg_off = struct.unpack(">I", self.header[0x54:0x58])[0]
            jpeg_len = struct.unpack(">I", self.header[0x58:0x5c])[0]
            meta_off = struct.unpack(">I", self.header[0x5c:0x60])[0]
            meta_len = struct.unpack(">I", self.header[0x60:0x64])[0]
            raw_off = struct.unpack(">I", self.header[0x64:0x68])[0]

            f.seek(jpeg_off)
            self.jpeg_data = f.read(jpeg_len)

            f.seek(meta_off)
            self.meta_data = bytearray(f.read(meta_len))

            f.seek(raw_off)
            self.raw_head = bytearray(f.read(2048))

        self.source_path = os.path.abspath(self.template_path)
        self.is_uncompressed = (struct.unpack(">I", self.header[0x6C:0x70])[0] == 0)
        raw_model = self.header[0x1c:0x3c]
        self.camera_model = raw_model.decode("utf-8", errors="replace").strip("\x00").strip()
        self.is_non_gfx = ("GFX" not in self.camera_model.upper())

        # Parse CFA meta directory tags
        if len(self.meta_data) >= 4:
            num_entries = struct.unpack(">I", self.meta_data[:4])[0]
            curr = 4
            for _ in range(num_entries):
                if curr + 4 > len(self.meta_data):
                    break
                tag, length = struct.unpack(">HH", self.meta_data[curr:curr+4])
                doff = curr + 4
                val = self.meta_data[doff:doff+length]
                if tag == 0x0100 and len(val) >= 4:
                    self.height, self.width = struct.unpack(">HH", val[:4])
                elif tag == 0x0110 and len(val) >= 4:
                    self.default_crop_top, self.default_crop_left = struct.unpack(">HH", val[:4])
                elif tag == 0x0111 and len(val) >= 4:
                    self.default_crop_h, self.default_crop_w = struct.unpack(">HH", val[:4])
                elif tag == 0x0141 and len(val) >= 2:
                    self.bits_per_sample = struct.unpack(">H", val[:2])[0]
                curr += 4 + length

        # Parse raw_head SubIFD
        if len(self.raw_head) >= 52:
            rw = struct.unpack("<I", self.raw_head[36:40])[0]
            rh = struct.unpack("<I", self.raw_head[48:52])[0]
            if rw > 0 and rh > 0:
                self.width = rw
                self.height = rh

        endian = "<" if self.raw_head.startswith(b"II") else ">"
        if len(self.raw_head) >= 8:
            first_ifd = struct.unpack(endian + "I", self.raw_head[4:8])[0]
            sub_off = 26
            if first_ifd + 2 <= len(self.raw_head):
                num_tags = struct.unpack(endian + "H", self.raw_head[first_ifd:first_ifd+2])[0]
                pos = first_ifd + 2
                for _ in range(num_tags):
                    if pos + 12 > len(self.raw_head):
                        break
                    t, dt, c, v = struct.unpack(endian + "HHI I", self.raw_head[pos:pos+12])
                    if t == 0xf000:
                        sub_off = v
                        break
                    pos += 12

            if sub_off + 2 <= len(self.raw_head):
                num_sub = struct.unpack(endian + "H", self.raw_head[sub_off:sub_off+2])[0]
                pos = sub_off + 2
                for _ in range(num_sub):
                    if pos + 12 > len(self.raw_head):
                        break
                    t, dt, c, v = struct.unpack(endian + "HHI I", self.raw_head[pos:pos+12])
                    self.subifd_offsets[t] = v
                    pos += 12

        if 0xf007 in self.subifd_offsets:
            strip_off = self.subifd_offsets[0xf007]
            if 0 < strip_off <= len(self.raw_head):
                self.raw_head = self.raw_head[:strip_off]

        if 0xf00a in self.subifd_offsets:
            bl_off = self.subifd_offsets[0xf00a]
            if bl_off + 4 <= len(self.raw_head):
                bl_val = struct.unpack("<I", self.raw_head[bl_off:bl_off+4])[0]
                if bl_val > 0:
                    self.black_level = bl_val


class RawToRafConverter:
    """Converts camera RAW files to Fujifilm RAF using GFX 100S II structure."""

    GFX_WIDTH = 11808
    GFX_HEIGHT = 8754
    GFX_CROP_W = 11648
    GFX_CROP_H = 8736
    GFX_BLACK_LEVEL = 1024

    def __init__(self, dnglab_path: Optional[str] = None, container_input: Any = None, auto_container: bool = False):
        self.dnglab_path = dnglab_path or self._find_dnglab()
        self.container_pool = self._resolve_containers(container_input, auto_container)
        print(f"[*] Container Pool: loaded {len(self.container_pool)} container template(s):")
        distinct = {}
        for t in sorted(self.container_pool, key=lambda x: x.width * x.height):
            key = (t.width, t.height, t.camera_model)
            if key not in distinct:
                distinct[key] = t
        for t in distinct.values():
            model_disp = f"{t.camera_model} (spoofed to GFX50S II)" if t.is_non_gfx else t.camera_model
            fname = os.path.basename(t.source_path)
            print(f"    - {model_disp:<30} (Canvas: {t.width:>5} x {t.height:>5}, Bits: {t.bits_per_sample}) [from '{fname}']")

    def _resolve_containers(self, container_input: Any, auto_container: bool) -> list:
        paths = []

        def scan_dir(d):
            if os.path.isdir(d):
                for f in sorted(os.listdir(d)):
                    if f.lower().endswith(".raf"):
                        paths.append(os.path.abspath(os.path.join(d, f)))

        inputs = []
        if isinstance(container_input, (list, tuple)):
            inputs = list(container_input)
        elif isinstance(container_input, str):
            inputs = [container_input]

        if not inputs or auto_container or any(i == "auto" for i in inputs):
            if os.path.isdir("container"):
                scan_dir("container")
            if os.path.exists("DSCF0260.RAF"):
                paths.append(os.path.abspath("DSCF0260.RAF"))

        for inp in inputs:
            if inp == "auto":
                continue
            for part in inp.split(","):
                part = part.strip()
                if not part:
                    continue
                if os.path.isdir(part):
                    scan_dir(part)
                elif os.path.isfile(part):
                    paths.append(os.path.abspath(part))
                else:
                    cand = self._find_candidate([part, os.path.join("container", part)])
                    if cand:
                        paths.append(cand)
                    else:
                        print(f"    -> [WARNING] Specified container not found: {part}")

        seen = set()
        templates = []
        for p in paths:
            if p not in seen:
                seen.add(p)
                try:
                    t = Gfx100sIITemplate(p)
                    templates.append(t)
                except Exception:
                    pass

        if not templates:
            raise FileNotFoundError("No valid Fujifilm RAF container templates found. Specify --container <PATH> or place files in container/.")

        return templates

    def select_best_fitting(self, width: int, height: int) -> Gfx100sIITemplate:
        candidates = [t for t in self.container_pool if t.width >= width and t.height >= height]
        if candidates:
            candidates.sort(key=lambda t: (
                t.width * t.height,
                not t.is_uncompressed,
                t.is_non_gfx
            ))
            return candidates[0]
        return max(self.container_pool, key=lambda t: (t.width * t.height, t.is_uncompressed))

    def _find_candidate(self, candidates: List[str]) -> Optional[str]:
        for c in candidates:
            if os.path.exists(c):
                return os.path.abspath(c)
        return None

